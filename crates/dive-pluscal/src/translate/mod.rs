/// Pinned translator fairness selection, applied before process normalization.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum FairnessOption {
    /// Preserve explicit source declarations (the pinned default).
    #[default]
    Declared,
    /// Suppress generated fairness (`-nof`), except a sequential `--fair` source.
    None,
    /// Supply weak fairness for otherwise unfair processes (`-wf`).
    Weak,
    /// Supply strong fairness for otherwise unfair processes (`-sf`).
    Strong,
    /// Add weak fairness of the complete next action (`-wfNext`).
    Next,
}

/// Native translator resource settings; historical/options parity remains pending.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TranslationOptions {
    /// Source parser limits.
    pub parser: Options,
    /// Insert missing labels even when the source already has labels (`-label`).
    /// Sequential sources without labels enable insertion by default; process
    /// bodies always require this option when a label is missing.
    pub insert_missing_labels: bool,
    /// Prefix of generated labels (`-labelRoot`); this does not enable insertion.
    pub label_root: String,
    /// Process/default fairness (`-nof`, `-wf`, `-sf`, `-wfNext`).
    #[serde(default)]
    pub fairness: FairnessOption,
    /// Maximum labelled actions (hard ceiling: 10,000).
    pub max_actions: usize,
    /// Maximum generated bytes (hard ceiling: 4 MiB).
    /// Also bounds process/procedure fairness construction work before expansion.
    pub max_output_bytes: usize,
}
impl Default for TranslationOptions {
    fn default() -> Self {
        Self {
            parser: Options::default(),
            insert_missing_labels: false,
            label_root: "Lbl_".into(),
            fairness: FairnessOption::Declared,
            max_actions: 10_000,
            max_output_bytes: 4_194_304,
        }
    }
}

/// The stage deciding a translation failure.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum TranslationStage {
    /// Lexing/source grammar failed.
    Source,
    /// Labels, names or control flow failed admission.
    Normalization,
    /// Generated expression/action construction failed.
    Generation,
}

/// A translation failure never carries a partially accepted artifact.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TranslationError {
    /// Deciding stage, separate from source grammar acceptance.
    pub stage: TranslationStage,
    /// Stable diagnostic over original source.
    pub diagnostic: Diagnostic,
}
impl std::fmt::Display for TranslationError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.diagnostic.fmt(formatter)
    }
}
impl std::error::Error for TranslationError {}

/// An artifact region and its original PlusCal source region.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TranslationMap {
    /// UTF-8 bytes in the generated TLA body.
    pub generated: Span,
    /// UTF-8 bytes in original source.
    pub original: Span,
}

/// A nonfatal normalization observation, never a successful check verdict.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TranslationWarning {
    /// Stable observation code.
    pub code: String,
    /// Original PlusCal source bytes.
    pub span: Span,
    /// Human-readable detail.
    pub message: String,
}

/// A generated label associated with its original statement, not a source token.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct InsertedLabel {
    /// Generated action name.
    pub name: String,
    /// Original statement extent.
    pub source: Span,
    /// Original one-based reference statement position (C `with` uses its `(`).
    pub position: crate::ast::Position,
    /// Macro definition statement extent, when the label arose from expansion.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub macro_definition: Option<Span>,
    /// Definition position paired with the existing call-site `position`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub macro_definition_position: Option<crate::ast::Position>,
}

/// Admitted process storage context, never an evaluated process-domain claim.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ProcessTranslation {
    /// Original process operator spelling.
    pub name: String,
    /// Constant ID versus membership domain.
    pub binding_kind: crate::ast::BindingKind,
    /// Original ID/domain expression bytes.
    pub id_source: Span,
    /// Local storage variables, scalar for constant IDs and indexed for sets.
    pub local_variables: Vec<String>,
    /// Original complete process bytes.
    pub source: Span,
}

/// A native generated TLA body, without file checksums or translator map format.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Translation {
    /// Generated operator/declaration body, not a complete enclosing module.
    pub tla: String,
    /// Native source associations. This is not TLC's translator map file.
    pub mappings: Vec<TranslationMap>,
    /// Labelled actions in the original translator's expansion order.
    pub actions: Vec<String>,
    /// Original translator's program-counter optimization decision.
    pub program_counter: bool,
    /// Nonfatal normalization observations with original spans.
    pub warnings: Vec<TranslationWarning>,
    /// Inserted labels in the reference normalization traversal order.
    pub inserted_labels: Vec<InsertedLabel>,
    /// Required TLC configuration text for default model-value initialization.
    /// Empty when every global/process-local variable has an explicit initializer.
    pub configuration: String,
    /// Admitted process declarations; empty for sequential translation.
    pub processes: Vec<ProcessTranslation>,
    /// Requested and effective source/CLI settings used for this artifact.
    pub option_context: TranslationContext,
}

fn error(
    stage: TranslationStage,
    code: Code,
    span: Span,
    message: impl Into<String>,
) -> TranslationError {
    TranslationError {
        stage,
        diagnostic: Diagnostic {
            code,
            span,
            message: message.into(),
        },
    }
}

/// Find the reference-style source option header before hiding old output.
///
/// This callback-free alias preserves the original header diagnostic extent.
/// It does not parse arguments or certify admission. Resolved declarations carry
/// the full extent used for overlap checks; callers enforce their byte limit.
#[must_use]
pub fn source_option_declaration_span(source: &str) -> Option<Span> {
    source_options_span(source)
}

/// Translates a bounded sequential or disjoint finite-process current C/P algorithm.
/// Unproved process domains, procedure/macro interactions, historical modes and name
/// disambiguation fail before an artifact is returned. Expression validation and
/// complete module binding are separate stages.
///
/// # Errors
/// Named source, normalization, generation or resource diagnostics.
pub fn translate(
    source: &str,
    options: &TranslationOptions,
) -> Result<Translation, TranslationError> {
    translate_at(source, 0..source.len(), options)
}

/// Translates a selected algorithm in original module source.
/// Original byte spans are preserved. Each call joins a 16 MiB scoped worker;
/// the translator never invokes Java or writes files.
///
/// # Errors
/// Named source, normalization, generation or resource diagnostics.
pub fn translate_at(
    source: &str,
    region: std::ops::Range<usize>,
    options: &TranslationOptions,
) -> Result<Translation, TranslationError> {
    std::thread::scope(|scope| {
        let worker = std::thread::Builder::new()
            .name("dive-pluscal-translator".into())
            .stack_size(16 * 1024 * 1024)
            .spawn_scoped(scope, || {
                let parsed =
                    crate::parse_at(source, region, &options.parser).map_err(|diagnostic| {
                        TranslationError {
                            stage: TranslationStage::Source,
                            diagnostic,
                        }
                    })?;
                let context = resolve_translation_options(source, options)?;
                generate(source, &parsed, &context).map_err(|mut failure: TranslationError| {
                    if failure.diagnostic.span == Span::default() {
                        failure.diagnostic.span = parsed.algorithm.span;
                    }
                    failure
                })
            })
            .map_err(|failure| {
                error(
                    TranslationStage::Normalization,
                    Code::Resource,
                    Span::default(),
                    format!("cannot start PlusCal translator: {failure}"),
                )
            })?;
        worker.join().map_err(|_| {
            error(
                TranslationStage::Generation,
                Code::Internal,
                Span::default(),
                "PlusCal translation worker failed; report this input as a bug",
            )
        })?
    })
}

fn fairness_name(fairness: FairnessOption) -> &'static str {
    match fairness {
        FairnessOption::Declared => "",
        FairnessOption::None => "nof",
        FairnessOption::Weak => "wf",
        FairnessOption::Strong => "sf",
        FairnessOption::Next => "wfNext",
    }
}

/// Runs the translator and packages its output.
fn generate(
    source: &str,
    parsed: &crate::Parsed,
    context: &TranslationContext,
) -> Result<Translation, TranslationError> {
    let options = &context.effective;
    let root = &options.label_root;
    if root.len() > 256 {
        return Err(error(
            TranslationStage::Normalization,
            Code::Resource,
            parsed.algorithm.span,
            "PlusCal label-root byte limit (256) reached",
        ));
    }
    let mut chars = root.chars();
    if !chars.next().is_some_and(|c| c.is_ascii_alphabetic())
        || !chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
    {
        return Err(error(
            TranslationStage::Normalization,
            Code::Label,
            parsed.algorithm.span,
            "Label root must be a valid PlusCal identifier (must start with a letter and contain only letters, numbers, and underscores)",
        ));
    }
    let settings = pcal::Settings {
        label: options.insert_missing_labels,
        label_root: root.clone(),
        fairness: fairness_name(options.fairness).to_owned(),
        max_depth: options.parser.max_depth.min(256),
        ..pcal::Settings::default()
    };
    let output = pcal::translate(parsed, &settings).map_err(|failure| {
        let span = failure.at.map_or(Span::default(), |at| {
            parsed
                .tokens
                .iter()
                .find(|t| t.span.start >= at)
                .map_or(Span { start: at, end: at }, |t| t.span)
        });
        let stage = if failure.code == Code::Internal {
            TranslationStage::Generation
        } else {
            TranslationStage::Normalization
        };
        error(stage, failure.code, span, failure.message)
    })?;
    if output.actions.len() > options.max_actions.min(10_000) {
        return Err(error(
            TranslationStage::Generation,
            Code::Resource,
            parsed.algorithm.span,
            "PlusCal labelled-action limit reached",
        ));
    }
    let tla = output.lines.join("\n");
    if tla.len() > options.max_output_bytes.min(4_194_304) {
        return Err(error(
            TranslationStage::Generation,
            Code::Resource,
            parsed.algorithm.span,
            "PlusCal generated-output byte limit reached",
        ));
    }
    let _ = source;
    // Source expressions are scanned, not parsed, so a generated body can be
    // malformed (pcal.trans then writes it anyway). Never return one.
    let module = format!("---- MODULE NativePlusCal ----\nEXTENDS TLC\n{tla}\n====\n");
    if !dive_syntax::parse_module(&module).is_ok() {
        return Err(error(
            TranslationStage::Generation,
            Code::Expression,
            parsed.algorithm.span,
            "generated TLA syntax rejected; source expression validation failed",
        ));
    }
    let processes = match &parsed.algorithm.body {
        crate::ast::Body::Processes(list) => list
            .iter()
            .zip(&output.processes)
            .map(|(process, info)| ProcessTranslation {
                name: info.name.clone(),
                binding_kind: process.id.kind,
                id_source: process.id.expression.span,
                local_variables: info.local_variables.clone(),
                source: process.span,
            })
            .collect(),
        crate::ast::Body::Sequential(_) => Vec::new(),
    };
    let warnings = if output.renamed.is_empty() {
        Vec::new()
    } else {
        vec![TranslationWarning {
            code: "symbols-renamed".into(),
            span: parsed.algorithm.span,
            message: "symbols were renamed.".into(),
        }]
    };
    Ok(Translation {
        tla,
        mappings: Vec::new(),
        actions: output.actions,
        program_counter: output.program_counter,
        warnings,
        inserted_labels: output
            .added_labels
            .iter()
            .map(|label| InsertedLabel {
                name: label.name.clone(),
                source: Span {
                    start: label.at,
                    end: label.at,
                },
                position: crate::ast::Position {
                    line: label.line,
                    column: label.column,
                },
                macro_definition: None,
                macro_definition_position: None,
            })
            .collect(),
        configuration: if output.default_init {
            "CONSTANT defaultInitValue = defaultInitValue\n".into()
        } else {
            String::new()
        },
        processes,
        option_context: context.clone(),
    })
}

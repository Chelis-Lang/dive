#!/usr/bin/env python3
"""Write SANY's verdict for each corpus test case.

Usage: corpus_verdicts.py INDEX.json SANY.jsonl OUT.txt

INDEX.json comes from extract_corpus.py; SANY.jsonl from run_sany.py over
the extracted Test.tla files. A `name_mismatch` result counts as accept: the
parser accepted the module and only SANY's file-name check failed.
"""
import json
import sys


def main():
    index = {e["id"]: e for e in json.load(open(sys.argv[1]))}
    verdicts = {}
    for line in open(sys.argv[2]):
        r = json.loads(line)
        test_id = r["path"].rstrip("/").split("/")[-2]
        verdicts[test_id] = "accept" if r["verdict"] in ("accept", "name_mismatch") else "reject"
    with open(sys.argv[3], "w") as out:
        out.write("# Generated by crates/dive-syntax/acceptance/corpus_verdicts.py from the pinned\n")
        out.write("# SANY (tla2tools.jar sha256 7beec0f04818732a62fa193731711a99aa4f11279499b2360a7d156c519ea78d).\n")
        out.write("# Do not edit. Format: <file>\\t<test name>\\t<accept|reject>\n")
        for test_id in sorted(index):
            e = index[test_id]
            name = e["name"].replace("\t", " ").replace("\n", " ")
            out.write("%s\t%s\t%s\n" % (e["file"], name, verdicts[test_id]))


if __name__ == "__main__":
    main()

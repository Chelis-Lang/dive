#!/usr/bin/env python3
"""Write SANY parser verdicts per file: verdicts.py SANY.jsonl ROOT OUT.txt

Paths are written relative to ROOT. `name_mismatch` counts as accept (the
parser accepted; only SANY's file-name check failed).
"""
import json
import os
import sys


def main():
    sany, root, out = sys.argv[1:4]
    rows = []
    for line in open(sany):
        r = json.loads(line)
        if r["verdict"] == "crash":
            continue
        v = "accept" if r["verdict"] in ("accept", "name_mismatch") else "reject"
        rows.append((os.path.relpath(r["path"], root), v))
    with open(out, "w") as fh:
        fh.write("# Generated by crates/dive-syntax/acceptance/verdicts.py from the pinned SANY\n")
        fh.write("# (tla2tools.jar sha256 7beec0f04818732a62fa193731711a99aa4f11279499b2360a7d156c519ea78d).\n")
        fh.write("# Do not edit. Format: <file>\\t<accept|reject>\n")
        for p, v in sorted(rows):
            fh.write("%s\t%s\n" % (p, v))


if __name__ == "__main__":
    main()

//! Recheck edited safety invariants over an exact Core discovery order.
//!
//! A capture represents one immutable in-process search. Completed searches
//! can establish safety. A refutation retains a prefix which can decide only
//! a false invariant reached within that prefix. A miss requires an ordinary
//! fresh check for any verdict. See the Rust API guide for the admitted subset.

mod identity;
mod rows;

use crate::{AnalyzeOptions, AnalyzeReport, ConfigReport, core_engine};
use dive_core::{Machine, Opts, memo::Memo};
use dive_trace::{Ending, TraceDoc};
use identity::Identity;
use rows::Rows;
use std::{path::Path, sync::Arc};

/// Exact deterministic state/depth limits and a separate cap on retained rows.
/// Each retained row costs one word per state variable plus its parent/counters.
/// The cap does not bound the rest of the checker or enforce a wall deadline.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Limits {
    /// Maximum number of distinct states admitted by ordinary Core.
    pub max_states: Option<u64>,
    /// Maximum search depth admitted by ordinary Core.
    pub max_depth: Option<u64>,
    /// Maximum number of retained rows, including a possible failed endpoint.
    pub max_rows: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            max_states: None,
            max_depth: None,
            max_rows: 1_000_000,
        }
    }
}

/// A named non-deciding miss. Use the current ordinary checker to obtain a verdict.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Miss(String);
impl std::fmt::Display for Miss {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.0.fmt(f)
    }
}
impl std::error::Error for Miss {}
fn miss(reason: impl Into<String>) -> Miss {
    Miss(reason.into())
}

/// Exact observable counters for the deciding search position. On a recheck
/// these are reconstructed from the original ordered visits. No successors
/// are generated by the scan.
pub use dive_explore::Stats as Counts;

/// A completed safety proof or a freshly validated invariant violation.
#[derive(Debug)]
pub enum Decision {
    /// The complete closure satisfies every configured invariant.
    Holds(Counts),
    /// The first false configured invariant at its first failing new state.
    Refuted {
        /// The currently configured violated invariant.
        property: String,
        /// Counts at this decision in the unchanged transition system.
        counts: Counts,
        /// Current named finite witness, independently validated by dive-trace.
        trace: Box<TraceDoc>,
    },
}

impl Decision {
    /// Exact counters at this decision.
    #[must_use]
    pub fn counts(&self) -> Counts {
        match self {
            Self::Holds(n) | Self::Refuted { counts: n, .. } => *n,
        }
    }
}

/// An immutable, freshly bound single-worker safety program. Its fixed policy
/// uses the Dive profile, exact identity, seed and fingerprint zero, and the configured deadlock check. Programs have no host grants.
pub struct Program {
    identity: Arc<Identity>,
    cfg: dive_config::ModelConfig,
    prepared: core_engine::Prepared,
}

impl Program {
    /// Load both files once. Imports resolve through the ordinary Dive loader.
    ///
    /// # Errors
    /// A file, admission, binding or compile failure is a non-deciding miss.
    pub fn load(file: &Path, config: &Path) -> Result<Self, Miss> {
        let analysis = crate::analyze_file(file, &AnalyzeOptions::default())
            .map_err(|e| miss(e.to_string()))?;
        let config = crate::parse_config_file(config).map_err(|e| miss(e.to_string()))?;
        Self::from_reports(&analysis, &config)
    }

    /// Bind the exact immutable source and configuration already analyzed by
    /// the caller. Imports and the syntax used for identity come from the same
    /// analysis as the lowered executable IR.
    ///
    /// # Errors
    /// Rejected source, unsupported model roles or compilation failures.
    pub fn from_reports(analysis: &AnalyzeReport, config: &ConfigReport) -> Result<Self, Miss> {
        if !analysis.accepted() {
            return Err(miss("source analysis failed"));
        }
        if !config.accepted() {
            return Err(miss("configuration rejected"));
        }
        let cfg = config
            .config()
            .ok_or_else(|| miss("configuration rejected"))?;
        let analysis = analysis.analysis();
        let identity = Identity::new(analysis, cfg)?;
        let ir = Arc::new(dive_ir::lower(analysis).map_err(|e| miss(format!("lowering: {e:?}")))?);
        if !dive_model::local_java_class_digests(&ir)
            .map_err(miss)?
            .is_empty()
        {
            return Err(miss("local Java module override"));
        }
        let mut options = dive_runtime::CheckOptions::dive(0);
        options.store = dive_store::StoreMode::Exact;
        let prepared = core_engine::prepare(&ir, cfg, &options, false, Opts::default(), false)
            .map_err(|r| miss(format!("binding or compilation: {:?}", r.verdict)))?;
        // The binder installs a supported local class by replacing its IR.
        // Catch even a class that appeared between the identity read and bind.
        if !Arc::ptr_eq(&ir, &prepared.model.ir) || prepared.start.has_diagnostics() {
            return Err(miss(
                "bound model changed IR or produced startup diagnostics",
            ));
        }
        let plan = &prepared.plan;
        if plan.vars.is_empty()
            || plan.effects.any
            || plan.effects.level
            || plan.symmetry.is_some()
            || plan.view.is_some()
            || !plan.constraints.is_empty()
            || !plan.action_constraints.is_empty()
            || !plan.implied_actions.is_empty()
            || !plan.implied_inits.is_empty()
        {
            return Err(miss("requires a pure, unreduced ordinary invariant plan"));
        }
        Ok(Self {
            identity: Arc::new(identity),
            cfg: cfg.clone(),
            prepared,
        })
    }

    /// Run Core once and retain its actual checked discovery order.
    ///
    /// # Errors
    /// Unsupported row types, exhausted limits, evaluator failure, a deadlock,
    /// or any ending other than complete success or a certified invariant violation.
    pub fn capture(&self, limits: Limits) -> Result<(Artifact, Decision), Miss> {
        let prepared = &self.prepared;
        let mut rows = Rows::new(prepared.plan.vars.len(), limits.max_rows);
        let out = dive_explore::explore_with_storage(
            &prepared.plan,
            &prepared.store,
            dive_explore::Config {
                opts: Opts::default(),
                workers: 1,
                warn: true,
                max_states: limits.max_states,
                max_depth: limits.max_depth,
                sample: None,
            },
            &|| false,
            Some(&mut rows),
            None,
            &dive_explore::storage::Storage {
                exact: true,
                ..Default::default()
            },
        );
        if let Some(error) = rows.refusal() {
            return Err(error);
        }
        if !out.warnings.is_empty() || !out.printed.is_empty() {
            return Err(miss("producer emitted a warning or output"));
        }
        let decision = match &out.verdict {
            dive_explore::Verdict::Success if out.stats.left_on_queue == 0 => {
                Decision::Holds(out.stats)
            }
            dive_explore::Verdict::InvariantViolated { property, .. } => {
                let trace = out
                    .trace
                    .as_ref()
                    .and_then(|res| res.as_ref().ok())
                    .ok_or_else(|| miss("producer trace unavailable"))?;
                rows.append_violation(trace)?;
                let id = rows.len() - 1;
                if rows.counts(id) != out.stats {
                    return Err(miss("producer prefix counters differ"));
                }
                self.certify(&rows, id, property)?
            }
            verdict => return Err(miss(format!("ineligible search ending: {verdict:?}"))),
        };
        if rows.len() as u64 != out.stats.distinct {
            return Err(miss("capture is incomplete"));
        }
        let complete = matches!(decision, Decision::Holds(_));
        Ok((
            Artifact {
                identity: self.identity.clone(),
                limits,
                rows,
                complete,
                original: out.stats,
            },
            decision,
        ))
    }

    fn certify(&self, rows: &Rows, id: usize, property: &str) -> Result<Decision, Miss> {
        let mut states = Vec::new();
        let mut labels = Vec::new();
        let mut cursor = Some(id);
        while let Some(i) = cursor {
            let mut state = serde_json::Map::new();
            for (name, h) in self.prepared.plan.vars.iter().zip(rows.row(i)) {
                let v = if let Some(n) = h.as_int() {
                    n.into()
                } else {
                    h.as_bool()
                        .ok_or_else(|| miss("non-scalar witness"))?
                        .into()
                };
                state.insert(name.clone(), v);
            }
            let label = rows
                .action(i)
                .map(|id| {
                    let model = &self.prepared.model;
                    let action = model
                        .actions
                        .get(id)
                        .ok_or_else(|| miss("unknown discovery action"))?;
                    Ok(
                        core_engine::action_name(model, action).map(|name| dive_trace::Label {
                            name,
                            location: Some(action.label().to_owned()),
                        }),
                    )
                })
                .transpose()?
                .flatten();
            labels.push(label);
            states.push(state);
            cursor = rows.parent(i);
        }
        states.reverse();
        labels.reverse();
        let trace = TraceDoc {
            variables: self.prepared.plan.vars.clone(),
            length: Some(states.len()),
            states,
            labels,
            ending: Some(Ending::Invariant(property.to_owned())),
            source: dive_trace::Source::Dive,
            properties: Vec::new(),
        };

        let model = dive_model::bind(
            Arc::clone(&self.prepared.model.ir),
            &self.cfg,
            &dive_model::BindOptions::dive(),
        )
        .map_err(|_| miss("independent validation binding failed"))?;
        if !Arc::ptr_eq(&model.ir, &self.prepared.model.ir) || !model.unsupported.is_empty() {
            return Err(miss("independent validation changed the bound model"));
        }
        if !dive_trace::validate_doc(&model, &trace, &self.cfg.model_values)
            .0
            .validation
            .is_valid()
        {
            return Err(miss(
                "independent validation did not certify the current ending",
            ));
        }
        Ok(Decision::Refuted {
            property: property.to_owned(),
            counts: rows.counts(id),
            trace: Box::new(trace),
        })
    }
}

/// Private, non-deserializable evidence from this running Core build.
/// Reuse it for multiple edits or drop it to release its retained rows.
pub struct Artifact {
    identity: Arc<Identity>,
    limits: Limits,
    rows: Rows,
    complete: bool,
    original: Counts,
}
impl Artifact {
    /// The original establishing search, including its actual stopping point.
    #[must_use]
    pub fn original_counts(&self) -> Counts {
        self.original
    }

    /// Evaluate the new configured invariants in declaration and discovery
    /// order on the original concrete rows. A prefix can establish a current
    /// refutation only. Errors before a later violation defer to fresh Core.
    ///
    /// # Errors
    /// A changed transition input or limit, an evaluation/validation failure,
    /// or exhausting a prior prefix without reaching a new violation.
    pub fn recheck(&self, program: &Program, limits: Limits) -> Result<Decision, Miss> {
        if self.limits != limits || !self.identity.compatible(&program.identity) {
            return Err(miss("transition inputs or limits changed"));
        }
        let prepared = &program.prepared;
        let keys = prepared
            .plan
            .code
            .sites
            .iter()
            .map(dive_core::plan::MemoSite::key_len)
            .collect::<Vec<_>>();
        let mut machine = Machine::new(
            prepared.store.clone(),
            prepared.plan.vars.len(),
            Opts::default(),
            Memo::new(&keys),
        );
        for id in 0..self.rows.len() {
            let hit = dive_explore::first_false_invariant(
                &mut machine,
                &prepared.plan,
                self.rows.row(id),
            )
            .map_err(|e| miss(format!("current invariant evaluation: {e}")))?;
            if !machine.warnings.is_empty() || !machine.printed.is_empty() {
                return Err(miss("current invariant emitted a warning or output"));
            }
            if let Some(index) = hit {
                return program.certify(&self.rows, id, &prepared.plan.invariants[index].name);
            }
        }
        if self.complete {
            Ok(Decision::Holds(self.original))
        } else {
            Err(miss("refutation prefix exhausted"))
        }
    }
}


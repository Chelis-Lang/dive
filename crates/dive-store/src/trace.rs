//! The trace log: parent pointers for counterexample replay (ADR 0015 §4).
//!
//! Distinct states are numbered in discovery order (𝒪 order): a state's id is the
//! number of states found before it. For each state the log records its parent's id
//! (none for an initial state) and its **ordinal**: its index among the parent's
//! successors in enumeration order, or among the initial states. That is 12 bytes per
//! state.
//!
//! A counterexample is rebuilt by replay: regenerate the initial states and take the
//! one at the root's ordinal, then repeatedly regenerate the successors of the current
//! state and take the one at the next ordinal. No fingerprint matching is involved.

use crate::error::StoreError;

/// A distinct state's number, in discovery order.
pub type StateId = u64;

/// The parent field of an initial state.
const ROOT: u64 = u64::MAX;

/// One step of a path: how to regenerate a state from its parent.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct TraceStep {
    /// The state's id.
    pub id: StateId,
    /// The parent's id, or `None` for an initial state.
    pub parent: Option<StateId>,
    /// The state's index among its parent's successors (or among the initial
    /// states), in enumeration order.
    pub ordinal: u32,
}

/// Parent pointers of every distinct state, in discovery order.
///
/// ```
/// use dive_store::trace::TraceLog;
///
/// let mut log = TraceLog::new();
/// let a = log.push_initial(0); // the first initial state
/// let b = log.push_initial(1);
/// let c = log.push(b, 3)?; // the 4th successor of `b`
/// let path: Vec<u32> = log.path(c)?.iter().map(|s| s.ordinal).collect();
/// assert_eq!(path, [1, 3]);
/// assert_eq!((a, b, c), (0, 1, 2));
/// # Ok::<(), dive_store::StoreError>(())
/// ```
#[derive(Clone, Debug, Default)]
pub struct TraceLog {
    parents: Vec<u64>,
    ordinals: Vec<u32>,
}

impl TraceLog {
    /// An empty log.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Records the next initial state, the `ordinal`-th generated by `Init`.
    pub fn push_initial(&mut self, ordinal: u32) -> StateId {
        let id = self.parents.len() as u64;
        self.parents.push(ROOT);
        self.ordinals.push(ordinal);
        id
    }

    /// Records the next state, the `ordinal`-th successor of `parent`.
    ///
    /// # Errors
    /// [`StoreError::BadParent`] unless `parent` is an earlier state.
    pub fn push(&mut self, parent: StateId, ordinal: u32) -> Result<StateId, StoreError> {
        let id = self.parents.len() as u64;
        if parent >= id {
            return Err(StoreError::BadParent { id, parent });
        }
        self.parents.push(parent);
        self.ordinals.push(ordinal);
        Ok(id)
    }

    /// The number of states recorded.
    #[must_use]
    pub fn len(&self) -> u64 {
        self.parents.len() as u64
    }

    /// Whether no state is recorded.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.parents.is_empty()
    }

    /// The record of state `id`.
    #[must_use]
    pub fn get(&self, id: StateId) -> Option<TraceStep> {
        let i = usize::try_from(id).ok()?;
        let parent = *self.parents.get(i)?;
        Some(TraceStep {
            id,
            parent: (parent != ROOT).then_some(parent),
            ordinal: *self.ordinals.get(i)?,
        })
    }

    /// The path from an initial state to `id`, root first.
    ///
    /// # Errors
    /// [`StoreError::UnknownState`] if `id` was never recorded.
    pub fn path(&self, id: StateId) -> Result<Vec<TraceStep>, StoreError> {
        let mut path = Vec::new();
        let mut cur = Some(id);
        while let Some(i) = cur {
            let step = self.get(i).ok_or(StoreError::UnknownState(i))?;
            path.push(step);
            // Parents are strictly earlier, so this terminates.
            cur = step.parent;
        }
        path.reverse();
        Ok(path)
    }

    /// The depth of state `id`: 1 for an initial state.
    ///
    /// # Errors
    /// [`StoreError::UnknownState`] if `id` was never recorded.
    pub fn depth(&self, id: StateId) -> Result<usize, StoreError> {
        self.path(id).map(|p| p.len())
    }

    /// Heap memory held, in bytes (12 per state, plus spare capacity).
    #[must_use]
    pub fn memory_bytes(&self) -> usize {
        self.parents.capacity() * 8 + self.ordinals.capacity() * 4
    }
}

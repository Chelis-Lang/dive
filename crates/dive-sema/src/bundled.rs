pub(crate) fn module(name: &str) -> Option<(&'static str, &'static str)> {
    MODULES
        .iter()
        .find(|(n, _, _)| *n == name)
        .map(|(_, library, source)| (*library, *source))
}

#[cfg(test)]
mod tests {
    use super::MODULES;

    #[test]
    fn every_bundled_module_parses_and_matches_its_file_name() {
        for (name, _, source) in MODULES {
            let parsed = dive_syntax::parse_module(source);
            assert!(parsed.is_ok(), "{name}: {:?}", parsed.diagnostics());
            assert!(
                parsed.check_file_name(&format!("{name}.tla")).is_none(),
                "{name}"
            );
        }
        assert_eq!(MODULES.len(), 48);
    }
}
